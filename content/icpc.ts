export interface IcpcProblem {
  letter: string;
  slug: string;
  title: string;
  archiveId: number;
  difficulty: 'Базова' | 'Легка' | 'Середня' | 'Складна';
  summary: string;
  patterns: { label: string; theoryId: string; signal: string }[];
  sections: { title: string; blocks: ContentBlock[] }[];
  complexity: string;
  pitfalls: string[];
}

const p = (text: string): ContentBlock => ({ type: 'paragraph', text });
const code = (code: string): ContentBlock => ({
  type: 'code',
  language: 'text',
  code,
  caption: 'Псевдокод · індексацію зазначено в поясненні',
});
const note = (title: string, text: string): ContentBlock => ({
  type: 'callout',
  title,
  text,
});
const section = (title: string, ...blocks: ContentBlock[]) => ({
  title,
  blocks,
});
const pattern = (label: string, theoryId: string, signal: string) => ({
  label,
  theoryId,
  signal,
});

